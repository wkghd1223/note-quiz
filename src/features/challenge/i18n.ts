export type ChallengeCopy = { [K in keyof typeof rows]: string } & {
  worldTitles: string[];
  worldObjectives: string[];
  stagesById: Record<string, { title: string; objective: string }>;
};
export function challengeCopy(language: string): ChallengeCopy {
  if (language === "ru") return russianChallenge;
  if (language === "ka") return georgianChallenge;
  if (language === "eo") return esperantoChallenge;
  const index = Math.max(
    0,
    ["en", "ko", "ja", "es", "de", "fr", "zh", "pt"].indexOf(language),
  );
  const copy = Object.fromEntries(
    Object.entries(rows).map(([key, values]) => [key, values[index]]),
  ) as { [K in keyof typeof rows]: string };
  return {
    ...copy,
    worldTitles: worldRows.map((row) => row[index]),
    worldObjectives: objectiveRows.map((row) => row[index]),
    stagesById: Object.fromEntries(
      stageRows.map((row, i) => [
        `w${Math.floor(i / 6) + 1}-s${(i % 6) + 1}`,
        {
          title: row[index],
          objective: objectiveRows[Math.floor(i / 6)][index],
        },
      ]),
    ),
  };
}
