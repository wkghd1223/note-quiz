export function importCopy(language: Language) {
  const index = SUPPORTED_LOCALES.indexOf(language);
  const strings = Object.fromEntries(
    Object.entries(rows).map(([key, row]) => [key, row[index]]),
  ) as Record<keyof typeof rows, string>;
  const c = challengeCopy(language),
    m = melodyCopy(language),
    t = getTranslation(language);
  return {
    ...strings,
    bar: c.measure,
    previous: c.previous,
    next: c.next,
    key: m.tonality,
    major: m.major,
    minor: m.minor,
    majorTonality: m.majorTonality,
    minorTonality: m.minorTonality,
    clef: t.settingsLabels.clef,
    clefNames: t.clefs,
    keySignature: t.settingsLabels.keySignature,
    meter: m.meter,
    apply: t.settingsLabels.apply,
    cancel: t.settingsLabels.cancel,
    close: t.ui.close,
    pitch: c.pitch,
    length: c.duration,
    rest: c.rest,
    accidental: t.settingsLabels.accidentals,
    loading: c.loading,
    retry: c.retry,
  };
}

export type ImportWords = ReturnType<typeof importCopy>;
